CREATE FUNCTION reject_duplicate_bms_ids() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    new_ids TEXT[] := array_remove(
        ARRAY[
            upper(btrim(NEW.bmb_id)), upper(btrim(NEW.cmb_id)),
            upper(btrim(NEW.rework_bmb_id)), upper(btrim(NEW.rework_cmb_id))
        ],
        ''
    );
BEGIN
    PERFORM pg_advisory_xact_lock(791204612);

    IF cardinality(new_ids) <> (
        SELECT count(DISTINCT bms_id)
        FROM unnest(new_ids) AS bms_values(bms_id)
    ) THEN
        RAISE EXCEPTION 'BMS IDs must be unique within a record'
            USING ERRCODE = '23505';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM bms_log AS existing
        CROSS JOIN LATERAL unnest(
            ARRAY[
                upper(btrim(existing.bmb_id)), upper(btrim(existing.cmb_id)),
                upper(btrim(existing.rework_bmb_id)), upper(btrim(existing.rework_cmb_id))
            ]
        ) AS existing_id(bms_id)
        JOIN unnest(new_ids) AS new_id(bms_id)
            ON new_id.bms_id = existing_id.bms_id
        WHERE existing.id IS DISTINCT FROM NEW.id
    ) THEN
        RAISE EXCEPTION 'BMS IDs must be unique across records'
            USING ERRCODE = '23505';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER bms_log_ids_unique
    BEFORE INSERT OR UPDATE OF bmb_id, cmb_id, rework_bmb_id, rework_cmb_id
    ON bms_log
    FOR EACH ROW EXECUTE FUNCTION reject_duplicate_bms_ids();

