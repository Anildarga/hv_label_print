CREATE FUNCTION reject_duplicate_dummy_module_ids() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    new_modules TEXT[] := array_remove(
        ARRAY[upper(btrim(NEW.m1)), upper(btrim(NEW.m2)), upper(btrim(NEW.m3)), upper(btrim(NEW.m4))],
        ''
    );
BEGIN
    PERFORM pg_advisory_xact_lock(791204611);

    IF cardinality(new_modules) <> (
        SELECT count(DISTINCT module_id)
        FROM unnest(new_modules) AS module_values(module_id)
    ) THEN
        RAISE EXCEPTION 'Module IDs must be unique within a dummy record'
            USING ERRCODE = '23505';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM dummy_log AS existing
        CROSS JOIN LATERAL unnest(
            ARRAY[
                upper(btrim(existing.m1)), upper(btrim(existing.m2)),
                upper(btrim(existing.m3)), upper(btrim(existing.m4))
            ]
        ) AS existing_module(module_id)
        JOIN unnest(new_modules) AS new_module(module_id)
            ON new_module.module_id = existing_module.module_id
        WHERE existing.id IS DISTINCT FROM NEW.id
    ) THEN
        RAISE EXCEPTION 'Module IDs must be unique across dummy records'
            USING ERRCODE = '23505';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER dummy_log_module_ids_unique
    BEFORE INSERT OR UPDATE OF m1, m2, m3, m4 ON dummy_log
    FOR EACH ROW EXECUTE FUNCTION reject_duplicate_dummy_module_ids();

